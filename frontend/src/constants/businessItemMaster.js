/**
 * 営業品目コードまたは名称を日本語名に変換する
 * コードが数値/数値文字列の場合はマスタから変換、それ以外は日本語名としてそのまま返す
 * @param {string|number} item
 * @returns {string}
 */
export function resolveBusinessItem(item) {
  if (item == null) return ''
  const str = String(item).trim()
  // 数値コードの場合
  const num = parseInt(str, 10)
  if (!isNaN(num) && BUSINESS_ITEM_MAP[num]) {
    return BUSINESS_ITEM_MAP[num]
  }
  // 文字列コードとして直接ルックアップ
  if (BUSINESS_ITEM_MAP[str]) return BUSINESS_ITEM_MAP[str]
  // 既に日本語名（マスタにない場合はそのまま返す）
  return str
}
